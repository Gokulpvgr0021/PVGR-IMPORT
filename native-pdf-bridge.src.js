import { Capacitor } from '@capacitor/core';
import { Directory, Filesystem } from '@capacitor/filesystem';
import { Share } from '@capacitor/share';

function safePdfName(name) {
  return String(name || 'GokulHub-Report.pdf').replace(/[\\/:*?"<>|]/g, '_');
}

async function saveBase64(name, base64) {
  const fileName = safePdfName(name);
  const saved = await Filesystem.writeFile({
    path: fileName,
    data: String(base64 || '').replace(/^data:application\/pdf;base64,/, ''),
    directory: Directory.Cache,
    recursive: true
  });

  await Share.share({
    title: fileName,
    text: 'PDF report generated by Gokul Hub',
    url: saved.uri,
    dialogTitle: 'Save or share PDF'
  });

  return saved;
}

window.GokulPdfBridge = {
  isNative: function () {
    return !!(Capacitor && typeof Capacitor.isNativePlatform === 'function' && Capacitor.isNativePlatform());
  },
  saveBase64: saveBase64
};
